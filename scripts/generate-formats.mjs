import {readFileSync,writeFileSync}from'node:fs';
import{z}from'zod';
const inventory=JSON.parse(readFileSync(new URL('../specs/upstream-inventory.json',import.meta.url)));
const entries=[];
for(const format of inventory.stringFormats){
 const schema=['date','time','datetime','duration'].includes(format)?z.iso[format]():z[format]();
 const pattern=schema.def.pattern;
 if(pattern instanceof RegExp){const flags=pattern.flags.replace(/u/g,'');entries.push([format,(flags?`(?${flags})`:'')+pattern.source]);}
}
for(const format of inventory.hashFormats){const [alg,enc]=format.split("_");entries.push([format,z.hash(alg,{enc}).def.pattern.source]);}
writeFileSync(new URL('../formats_generated.go',import.meta.url),'// Code generated by scripts/generate-formats.mjs from Zod '+z.core.version.major+'.'+z.core.version.minor+'.'+z.core.version.patch+'; DO NOT EDIT.\npackage zod2go\n\nvar builtinFormatPatterns=map[string]string{\n'+entries.map(([k,v])=>`${JSON.stringify(k)}:${JSON.stringify(v)},`).join('\n')+'\n}\n');
console.log(`Generated ${entries.length} format patterns`);
