import { writeFileSync } from 'node:fs';
import { z } from 'zod';
const pattern=z.core.regexes.emoji();
const ranges=[];let start=-1,end=-1;
for(let cp=0;cp<=0x10ffff;cp++){
 if(pattern.test(String.fromCodePoint(cp))){if(start<0)start=cp;end=cp}
 else if(start>=0){ranges.push([start,end]);start=-1}
}
if(start>=0)ranges.push([start,end]);
const output=`// Code generated by scripts/generate-emoji.mjs; DO NOT EDIT.\n// Unicode ${process.versions.unicode}, from Zod's Extended_Pictographic | Emoji_Component pattern.\npackage zod2go\n\nimport "sort"\n\nvar emojiRanges = [][2]rune{\n${ranges.map(([a,b])=>`{0x${a.toString(16)}, 0x${b.toString(16)}},`).join('\n')}\n}\n\nfunc validEmoji(s string) bool {\n if s=="" {return false}\n for _,r:=range s {i:=sort.Search(len(emojiRanges),func(i int)bool{return emojiRanges[i][1]>=r});if i==len(emojiRanges)||r<emojiRanges[i][0]{return false}}\n return true\n}\n`;
writeFileSync(new URL('../emoji_generated.go',import.meta.url),output);
console.log(`Generated ${ranges.length} emoji ranges for Unicode ${process.versions.unicode}`);
